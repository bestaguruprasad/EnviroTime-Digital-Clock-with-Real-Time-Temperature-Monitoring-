#include"types.h"
#define SETBIT(WORD,BITPOS)   (WORD|=(u32)1<<BITPOS)
#define CLRBIT(WORD,BITPOS)   (WORD&=~((u32)1<<BITPOS))
#define CPLBIT(WORD,BITPOS)   (WORD^=(u32)1<<BITPOS)
#define READBIT(WORD,BITPOS)  ((WORD>>BITPOS)&(u32)1)
#define READNIBBLE(WORD,STARTBITPOS)   ((WORD>>STARTBITPOS)&15)
#define READBYTE(WORD,STARTBITPOS)   ((WORD>>STARTBITPOS)&255)
#define WRITE2BIT(WORD,BITPOS,BITLEVEL)   WORD=((WORD&~((u32)1<<BITPOS))|(BITLEVEL<<BITPOS))
#define WRITENIBBLE(WORD,STARTBITPOS,NIBILVAL)   WORD=((WORD&~(15<<STARTBITPOS))|(NIBILVAL<<STARTBITPOS))
#define WRITEBYTE(WORD,STARTBITPOS,BYTEVAL)   WORD=((WORD&~(255<<STARTBITPOS))|(BYTEVAL<<STARTBITPOS))
#define READWRITEBIT(WORD,DBIT,SBIT)   WORD=((WORD&~((u32)1<<DBIT))|(SBIT<<DBIT))
#define READWRIBIT2(DWORD,DBIT,SWORD,SBIT)    DWORD=((DWORD&~((u32)1<<DBIT))|(((SWORD>>SBIT)&1)<<DBIT)) 										     
